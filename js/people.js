function phash(s) {
  var x = 0;
  for (var i = 0; i < String(s).length; i++) x = (x * 31 + String(s).charCodeAt(i)) >>> 0;
  return x;
}

/* Кто сейчас в этом месте: два-три имени из состава и строка на каждого.
   Выбор устойчив в пределах дня: пока день тот же, на экране те же люди. */
window.presentAt = function (S, node, phase) {
  var lines = (window.PRESENCE[node] || {})[phase] || (window.PRESENCE[node] || {}).day || [];
  if (!S || !S.roster || !S.roster.length || !lines.length) return [];
  var alive = [];
  for (var i = 0; i < S.roster.length; i++) {
    if (!S.roster[i].hero && S.roster[i].alive) alive.push(S.roster[i].name);
  }
  if (!alive.length) return [];
  var seed = phash(node + "|" + phase + "|" + (S.day || 1));
  var count = 2 + (seed % 2);
  var used = {}, out = [];
  for (var k = 0; k < count && k < alive.length; k++) {
    var idx = phash(node + phase + (S.day || 1) + "|" + k) % alive.length;
    var guard = 0;
    while (used[idx] && guard++ < alive.length) idx = (idx + 1) % alive.length;
    used[idx] = 1;
    out.push({
      name: alive[idx],
      line: lines[(seed + k) % lines.length]
    });
  }
  return out;
};

/* Имена всех живых, кроме героя, — из них движок берёт свидетелей. */
window.aliveNames = function (S) {
  var out = [];
  if (!S || !S.roster) return out;
  for (var i = 0; i < S.roster.length; i++) {
    if (!S.roster[i].hero && S.roster[i].alive) out.push(S.roster[i].name);
  }
  return out;
};

/* Один человек уходит, на его место приходит новый. */
window.removeFromRoster = function (S, name) {
  if (!S || !S.roster) return null;
  for (var i = 0; i < S.roster.length; i++) {
    var p = S.roster[i];
    if (p.hero || !p.alive || p.name !== name) continue;
    var next = (S.deck && S.deck.length) ? S.deck.shift() : null;
    if (!next) return null;
    S.roster[i] = { name: next, hero: false, alive: true, fate: "пришёл на место " + name };
    return { gone: name, came: next };
  }
  return null;
};
