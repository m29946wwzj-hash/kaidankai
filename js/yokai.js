/* Ёкаи и страх.

   Страх растёт в кайдане с каждым шагом. Пока он ниже предела, он только
   подсказывает: голос слышно ближе, шаг за спиной, воздух плотнее.
   Как только страх доходит до предела, в дом входит ёкай — и забирает
   не рассказчика, а того, кто пошёл с ним рядом. Гибнет человек из
   Кураямы, и это описано целиком: от первого движения до того, что
   остаётся на полу.

   Правило это жестокое, но честное: голос кормится страхом слушателя,
   а платит за него тот, кто пришёл следом. */

