window.KILLS = [killShadow, killCall, killMeasure];

/* Полное описание гибели. pick — счётчик смертей в городе: способы идут по кругу,
   чтобы два кайдана подряд не кончались одинаково. */
window.yokaiKill = function (name, pick) {
  var list = window.KILLS;
  var i = (pick | 0) % list.length;
  return list[i < 0 ? i + list.length : i](name);
};

