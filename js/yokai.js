/* Строка напряжения для сцены. Выбор устойчив: перерисовка не меняет текст. */
window.tensionLine = function (level, key) {
  var arr = window.TENSION[level];
  if (!arr || !arr.length) return "";
  var x = 0;
  for (var i = 0; i < String(key).length; i++) x = (x * 31 + String(key).charCodeAt(i)) >>> 0;
  return arr[x % arr.length];
};

