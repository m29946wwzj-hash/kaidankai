/* Собирает колоду из ста имён: сначала основные, потом запасные.
   Имена не повторяются, пока колода не кончится. */

window.makeDeck = function () {
  var seen = {}, deck = [], i;
  var all = window.NAMES.concat(window.RESERVE);
  for (i = 0; i < all.length; i++) {
    if (!seen[all[i]]) { seen[all[i]] = 1; deck.push(all[i]); }
  }
  for (i = deck.length - 1; i > 0; i--) {
    var j = Math.floor(Math.random() * (i + 1));
    var t = deck[i]; deck[i] = deck[j]; deck[j] = t;
  }
  return deck;
};

/* Сто участников: первый — игрок. */
window.makeRoster = function (heroName) {
  var deck = window.makeDeck();
  var roster = [{ name: heroName, hero: true, alive: true, fate: "" }];
  for (var i = 1; i < 100; i++) {
    roster.push({ name: deck[i - 1], hero: false, alive: true, fate: "" });
  }
  return { roster: roster, deck: deck.slice(99) };
};

/* Гибель участника: на его место приходит новый. */
window.replaceOne = function (S) {
  var alive = [];
  for (var i = 0; i < S.roster.length; i++) {
    if (!S.roster[i].hero && S.roster[i].alive) alive.push(i);
  }
  if (!alive.length) return null;
  var idx = alive[Math.floor(Math.random() * alive.length)];
  var dead = S.roster[idx].name;
  var next = S.deck.length ? S.deck.shift() : "безымянный";
  S.roster[idx] = { name: next, hero: false, alive: true, fate: "пришёл на место " + dead };
  return { gone: dead, came: next };
};
